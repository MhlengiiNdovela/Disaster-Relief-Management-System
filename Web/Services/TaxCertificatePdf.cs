using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Web.Services;

public sealed record DonationCertificateRequest(
    string DonorName,
    decimal Amount,
    string Currency,
    DateOnly DonationDate,
    string ReliefProjectTitle,
    string? CertificateNumber = null);

public static class TaxCertificatePdf
{
    public static byte[] Create(DonationCertificateRequest donation)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(50);
                page.Header().Text("Gift of the Givers").FontSize(24).Bold().FontColor(Colors.Blue.Darken2);
                page.Content().Column(column =>
                {
                    column.Spacing(10);
                    column.Item().Text("Donation Tax Certificate").FontSize(18).Bold();
                    if (!string.IsNullOrWhiteSpace(donation.CertificateNumber))
                    {
                        column.Item().Text($"Certificate number: {donation.CertificateNumber}");
                    }
                    column.Item().Text($"Donor: {donation.DonorName}");
                    column.Item().Text($"Amount: {donation.Currency} {donation.Amount:N2}");
                    column.Item().Text($"Donation date: {donation.DonationDate:yyyy-MM-dd}");
                    column.Item().Text($"Relief project: {donation.ReliefProjectTitle}");
                    column.Item().PaddingTop(20).Text("This placeholder certificate confirms receipt of the donation.");
                });
                page.Footer().AlignCenter().Text("Generated by the Disaster Relief Management System");
            });
        }).GeneratePdf();
    }
}
