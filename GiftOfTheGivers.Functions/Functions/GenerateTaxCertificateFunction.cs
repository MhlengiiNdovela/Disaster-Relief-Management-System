using System.Net;
using GiftOfTheGivers.Functions.Models;
using GiftOfTheGivers.Helpers;
using Microsoft.Azure.Functions.Worker;
using Microsoft.Azure.Functions.Worker.Http;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace GiftOfTheGivers.Functions.Functions;

public sealed class GenerateTaxCertificateFunction
{
    public GenerateTaxCertificateFunction()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    [Function("GenerateTaxCertificate")]
    public async Task<HttpResponseData> Run(
        [HttpTrigger(AuthorizationLevel.Anonymous, "post", Route = "generate-tax-certificate")] HttpRequestData request)
    {
        var donation = await request.ReadFromJsonAsync<DonationRequest>();
        if (donation is null || !DonationRules.IsValid(donation.DonorName, donation.Amount, donation.Currency))
        {
            var invalidResponse = request.CreateResponse(HttpStatusCode.BadRequest);
            await invalidResponse.WriteStringAsync("A donor name and a positive donation amount are required.");
            return invalidResponse;
        }

        var pdf = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(50);
                page.Header().Text("Gift of the Givers").FontSize(24).Bold().FontColor(Colors.Blue.Darken2);
                page.Content().Column(column =>
                {
                    column.Spacing(10);
                    column.Item().Text("Donation Tax Certificate").FontSize(18).Bold();
                    column.Item().Text($"Donor: {donation.DonorName}");
                    column.Item().Text($"Amount: {donation.Currency} {donation.Amount:N2}");
                    column.Item().Text($"Donation date: {donation.DonationDate:yyyy-MM-dd}");
                    column.Item().Text($"Relief project: {donation.ReliefProjectTitle}");
                    column.Item().PaddingTop(20).Text("This placeholder certificate confirms receipt of the donation.");
                });
                page.Footer().AlignCenter().Text("Generated by the Disaster Relief Management System");
            });
        }).GeneratePdf();

        var response = request.CreateResponse(HttpStatusCode.OK);
        response.Headers.Add("Content-Type", "application/pdf");
        response.Headers.Add("Content-Disposition", "attachment; filename=donation-tax-certificate.pdf");
        await response.Body.WriteAsync(pdf);
        return response;
    }
}